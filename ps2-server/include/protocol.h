#ifndef PFSNET_PROTOCOL_H
#define PFSNET_PROTOCOL_H

#include <stdint.h>

#define PFSNET_COMMAND_PORT 45061
#define PFSNET_DATA_PORT 45062
#define PFSNET_MAGIC 0x4E534650u /* 'PFSN' LE */
#define PFSNET_PROTOCOL_VERSION 0x0001u
#define PFSNET_MAX_CONTROL_PAYLOAD 131072u
#define PFSNET_HEADER_SIZE 12

#define PFSNET_FEAT_FILE_OPS (1u << 0)
#define PFSNET_FEAT_DATA_CHANNEL (1u << 1)
#define PFSNET_FEAT_APA_SECTOR (1u << 2)
#define PFSNET_FEAT_APA_MUTATE (1u << 3)
#define PFSNET_FEAT_STREAM_RING (1u << 4)

#define PFSNET_PUT_OVERWRITE (1u << 0)
#define PFSNET_PUT_RESUME (1u << 1)

#define PFSNET_CMD_HELLO 0x0001u
#define PFSNET_CMD_PING 0x0002u
#define PFSNET_CMD_MOUNT 0x0003u
#define PFSNET_CMD_UMOUNT 0x0004u
#define PFSNET_CMD_GET_SESSION 0x0005u
#define PFSNET_CMD_LIST_PARTITIONS 0x0010u
#define PFSNET_CMD_GET_APA_FREE 0x0011u
#define PFSNET_CMD_GET_PFS_FREE 0x0012u
#define PFSNET_CMD_LIST_DIR 0x0020u
#define PFSNET_CMD_MKDIR 0x0021u
#define PFSNET_CMD_RMDIR 0x0022u
#define PFSNET_CMD_REMOVE 0x0023u
#define PFSNET_CMD_RENAME 0x0024u
#define PFSNET_CMD_STAT 0x0025u
#define PFSNET_CMD_PUT_BEGIN 0x0030u
#define PFSNET_CMD_PUT_END 0x0031u
#define PFSNET_CMD_PUT_ABORT 0x0032u
#define PFSNET_CMD_GET_BEGIN 0x0033u
#define PFSNET_CMD_GET_END 0x0034u
#define PFSNET_CMD_GET_ABORT 0x0035u
#define PFSNET_CMD_READ_SECTORS 0x0040u
#define PFSNET_CMD_APA_CREATE_PFS 0x0050u
#define PFSNET_CMD_APA_REMOVE 0x0051u
#define PFSNET_CMD_APA_RENAME 0x0052u
#define PFSNET_CMD_SHUTDOWN 0x00FFu

#define PFSNET_OK 0
#define PFSNET_ERR_GENERIC (-1)
#define PFSNET_ERR_IO (-2)
#define PFSNET_ERR_NOENT (-3)
#define PFSNET_ERR_EXIST (-4)
#define PFSNET_ERR_NOT_EMPTY (-5)
#define PFSNET_ERR_NOSPC (-6)
#define PFSNET_ERR_INVAL (-7)
#define PFSNET_ERR_NOT_MOUNTED (-8)
#define PFSNET_ERR_BUSY (-9)
#define PFSNET_ERR_UNSUPPORTED (-10)
#define PFSNET_ERR_VERSION (-11)
#define PFSNET_ERR_MAGIC (-12)
#define PFSNET_ERR_DATA_CONN (-13)

typedef struct PfsNetPacketHdr
{
    uint32_t command;
    uint32_t payload_length;
    int32_t result;
} PfsNetPacketHdr;

#endif /* PFSNET_PROTOCOL_H */
